static long long now_ms(void)
{
	struct timespec ts;
	clock_gettime(CLOCK_MONOTONIC, &ts);
	return (long long)ts.tv_sec*1000 + ts.tv_nsec/1000000;
}

int main(int argc, char **argv)
{
	int port = atoi(argv[1]);
	int mode = (argc>2 && !strcmp(argv[2],"replay")) ? 1 : 0;
	int idx = 0;
	long long lastchange = 0;

	int sock = socket(AF_INET, SOCK_DGRAM, 0);
	struct sockaddr_in addr;
	memset(&addr, 0, sizeof(addr));
	addr.sin_family = AF_INET;
	addr.sin_addr.s_addr = INADDR_ANY;
	addr.sin_port = htons(port);
	if (bind(sock, (struct sockaddr*)&addr, sizeof(addr)) != 0) { perror("bind"); return 1; }
	printf("fakecsp listening on UDP %d\n", port);
	fflush(stdout);

	lastchange = now_ms();
	for (;;) {
		unsigned char buf[64];
		struct sockaddr_in from;
		socklen_t flen = sizeof(from);
		int n = recvfrom(sock, buf, sizeof(buf), 0, (struct sockaddr*)&from, &flen);
		if (n <= 0) continue;

		if (buf[0] == 3) { // PINGREQ -> PINGRPL + CARD_LIST
			unsigned char rep[16];
			rep[0] = 4;
			memcpy(rep+1, buf+1, 8);
			sendto(sock, rep, 9, 0, (struct sockaddr*)&from, flen);
			unsigned char cards[8];
			cards[0] = 0x13; cards[1] = 0x01; // CARD_LIST reset
			cards[2] = 0x26; cards[3] = 0x00; cards[4] = 0x00; cards[5] = 0x00; // caprov 2600:000000
			sendto(sock, cards, 6, 0, (struct sockaddr*)&from, flen);
			printf("ping-reply + cards\n"); fflush(stdout);
			continue;
		}
		if (buf[0] == 1 && n >= 12) { // TYPE_REQUEST
			long long t = now_ms();
			if (t - lastchange >= 2000) {
				idx = (idx + 1) % NCW;
				lastchange = t;
			}
			unsigned char rep[32];
			unsigned char *cw;
			if (mode && idx >= 8) cw = replaybad[(idx-8) % NREPLAYBAD];
			else cw = cwscript[idx];
			rep[0] = 2; // TYPE_REPLY
			memcpy(rep+1, buf+1, 11); // tag sid onid caid hash
			rep[12] = buf[1]; // tag
			memcpy(rep+13, cw, 16);
			sendto(sock, rep, 29, 0, (struct sockaddr*)&from, flen);
			printf("req hash=%02x%02x%02x%02x -> cw[%d] %02x%02x%02x%02x%02x%02x%02x%02x|%02x%02x%02x%02x%02x%02x%02x%02x\n",
				buf[8], buf[9], buf[10], buf[11], idx,
				cw[0],cw[1],cw[2],cw[3],cw[4],cw[5],cw[6],cw[7],
				cw[8],cw[9],cw[10],cw[11],cw[12],cw[13],cw[14],cw[15]);
			fflush(stdout);
			continue;
		}
	}
	return 0;
}
